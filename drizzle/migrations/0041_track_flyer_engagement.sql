CREATE TABLE public.flyer_engagement_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id UUID NOT NULL REFERENCES public.submissions(id) ON DELETE CASCADE,
  opened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

GRANT INSERT ON public.flyer_engagement_events TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.flyer_engagement_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.flyer_engagement_events_id_seq TO anon, authenticated, service_role;

ALTER TABLE public.flyer_engagement_events ENABLE ROW LEVEL SECURITY;

CREATE INDEX flyer_engagement_events_event_opened_idx
  ON public.flyer_engagement_events (event_id, opened_at DESC);
CREATE INDEX flyer_engagement_events_opened_idx
  ON public.flyer_engagement_events (opened_at DESC);

CREATE POLICY "Public flyer openings are recorded through the guarded function"
  ON public.flyer_engagement_events
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (false);

CREATE OR REPLACE FUNCTION public.increment_views(event_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
BEGIN
  UPDATE public.submissions
  SET views_count = COALESCE(views_count, 0) + 1
  WHERE id = $1;

  INSERT INTO public.flyer_engagement_events (event_id)
  SELECT s.id
  FROM public.submissions s
  WHERE s.id = $1
    AND s.image_url IS NOT NULL
    AND btrim(s.image_url) <> ''
    AND s.deleted_at IS NULL
    AND s.status IN ('aprovado', 'approved', 'published', 'publicado');
END;
$function$;

REVOKE ALL ON FUNCTION public.increment_views(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.increment_views(uuid) TO anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.intranet_flyer_engagement(
  p_start_at timestamptz,
  p_end_at timestamptz
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  result jsonb;
  use_hourly boolean;
BEGIN
  IF NOT public.intranet_can_access('marketing') THEN
    RAISE EXCEPTION 'Sem acesso ao Marketing' USING ERRCODE = '42501';
  END IF;

  IF p_start_at IS NULL OR p_end_at IS NULL OR p_end_at <= p_start_at OR p_end_at - p_start_at > interval '366 days' THEN
    RAISE EXCEPTION 'Período inválido';
  END IF;

  use_hourly := p_end_at - p_start_at <= interval '2 days';

  WITH eligible AS (
    SELECT
      s.id,
      COALESCE(NULLIF(btrim(s.event_title), ''), NULLIF(btrim(s.location), ''), 'Rolê sem título') AS title,
      COALESCE(s.published_at, s.approved_at, s.created_at) AS published_at,
      s.date AS event_date,
      CASE
        WHEN public.event_day_sp(s.date) < (now() AT TIME ZONE 'America/Sao_Paulo')::date THEN 'past'
        ELSE 'active'
      END AS lifecycle
    FROM public.submissions s
    WHERE s.image_url IS NOT NULL
      AND btrim(s.image_url) <> ''
      AND s.deleted_at IS NULL
      AND s.status IN ('aprovado', 'approved', 'published', 'publicado')
  ),
  counts AS (
    SELECT e.event_id, count(*)::integer AS total
    FROM public.flyer_engagement_events e
    WHERE e.opened_at >= p_start_at AND e.opened_at < p_end_at
    GROUP BY e.event_id
  ),
  trends AS (
    SELECT
      e.event_id,
      jsonb_agg(
        jsonb_build_object('bucket', e.bucket, 'value', e.value)
        ORDER BY e.bucket
      ) AS points
    FROM (
      SELECT
        f.event_id,
        CASE
          WHEN use_hourly THEN date_trunc('hour', f.opened_at AT TIME ZONE 'America/Sao_Paulo')
          ELSE date_trunc('day', f.opened_at AT TIME ZONE 'America/Sao_Paulo')
        END AS bucket,
        count(*)::integer AS value
      FROM public.flyer_engagement_events f
      WHERE f.opened_at >= p_start_at AND f.opened_at < p_end_at
      GROUP BY f.event_id, 2
    ) e
    GROUP BY e.event_id
  ),
  rows AS (
    SELECT
      a.id,
      a.title,
      a.published_at,
      a.event_date,
      a.lifecycle,
      COALESCE(c.total, 0) AS total,
      COALESCE(t.points, '[]'::jsonb) AS trend
    FROM eligible a
    LEFT JOIN counts c ON c.event_id = a.id
    LEFT JOIN trends t ON t.event_id = a.id
  ),
  summary AS (
    SELECT
      COALESCE(sum(total), 0)::integer AS total,
      COALESCE(round(COALESCE(sum(total), 0)::numeric / GREATEST(1, CEIL(EXTRACT(epoch FROM (p_end_at - p_start_at)) / 86400))), 0) AS daily_average
    FROM rows
  ),
  champion AS (
    SELECT id, title, total
    FROM rows
    WHERE total > 0
    ORDER BY total DESC, title
    LIMIT 1
  )
  SELECT jsonb_build_object(
    'summary', jsonb_build_object(
      'total', summary.total,
      'daily_average', summary.daily_average,
      'champion', (SELECT to_jsonb(champion) FROM champion)
    ),
    'items', COALESCE((
      SELECT jsonb_agg(to_jsonb(r) ORDER BY r.total DESC, r.published_at DESC)
      FROM rows r
    ), '[]'::jsonb),
    'granularity', CASE WHEN use_hourly THEN 'hour' ELSE 'day' END
  )
  INTO result
  FROM summary;

  RETURN result;
END;
$function$;

REVOKE ALL ON FUNCTION public.intranet_flyer_engagement(timestamptz, timestamptz) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.intranet_flyer_engagement(timestamptz, timestamptz) TO authenticated, service_role;